"""Battle-mode balance sweep: each stance preset and Pat's example behaviour against the default AI.

    python3 -I near/arena/battle_balance.py --json near/arena/battle-balance.json --md near/arena/BATTLE-BALANCE.md

Every table in TABLES (integer-13, then integer-14 with chase seeking out of view) is swept the same way; the JSON
keeps one run per table and `--tables` re-runs a subset. Every run is the real engine under that table, seeded hit
variance on, the newcomer
starter kit and the brawler style for everyone, so the behaviour is the only difference. Three compositions per
crowd size (2, 6, 10, 16), on fixed seeds:

- mixed: half the ring on the behaviour (rounded down, at least 1), the rest on the default AI. KO share, death
  share and survival per life of the behaviour group against its share of the ring; at size 2 this is the
  behaviour-vs-default 1v1, reported as a win rate beside the 60% target.
- all: the whole ring on the behaviour, to find stalls (a 60 s segment in which nobody is KO'd).
- baseline: the whole ring on the default AI, the reference for both.

follow-ally fighters protect the next follow-ally fighter in the ring; one with no partner names an absent ally,
so its protect drive idles. Nothing here tunes anything: a nerf is a new rules table and Pat's call.
"""

import argparse
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import battle_measure  # noqa: E402
import behaviour  # noqa: E402
import sim  # noqa: E402

MARKER = "<!-- generated by battle_balance.py below this line; findings above are written by hand -->"
SIZES = (2, 6, 10, 16)
SEEDS = {2: 24, 6: 12, 10: 8, 16: 6}
TICKS = 2400
FAIR_1V1_TARGET = 60          # P3's target, % of mirrored 1v1s (prd.md 4.9; a target, not a gate)
SHARE_BAR = 2.0               # P3/P4's bar: at most 2x fair share of KOs or survival at any crowd size
STALL_FLAG_PCT = 50           # a composition stalls when at least half of its 60 s segments see no KO
ABSENT = "no-partner"


def behaviours(rules):
    out = {name: {"v": 1, "stance": name} for name in sorted(rules["behaviour"]["stances"])}
    out["pats-example"] = battle_measure.EXAMPLE
    return out


def plan_for(raw, name, behaviour_names, rules=sim.DEFAULT_RULES):
    """The normalised plan for one fighter; follow-ally pairs with the next fighter on the same behaviour."""
    raw = json.loads(json.dumps(raw))
    if raw.get("stance") == "follow-ally":
        index = behaviour_names.index(name)
        partner = behaviour_names[index ^ 1] if (index ^ 1) < len(behaviour_names) else ABSENT
        raw["drives"] = {"protect_ally": partner}
    out, _, refused, _ = behaviour.normalise(raw, rules, name)
    if refused:
        raise ValueError(f"sweep behaviour refused for {name}: {refused}")
    return out


def run(seed, size, raw, count, ticks=TICKS, rules=sim.DEFAULT_RULES):
    """One ring: `count` fighters on `raw` (None = default AI), the rest default. Returns per-group totals."""
    game = sim.Sim(seed, rules)
    names = [f"f{i:02d}" for i in range(size)]
    # the behaviour fighters are spread evenly round the ring; count 0 (or no behaviour) is an all-default ring
    group = {name: ("b" if raw is not None and i * count // size != (i + 1) * count // size else "d")
             for i, name in enumerate(names)}
    for i, name in enumerate(names):
        game.enqueue(sim.Input(0, "join", name, 0, {"angle": i * 360 // size, "style": "brawler"}))
    on_plan = [n for n in names if group[n] == "b"] if raw is not None else []
    for name in on_plan:
        game.enqueue(sim.Input(1, "behaviour", name, 1, plan_for(raw, name, on_plan, rules)))
    alive = {name: 0 for name in names}
    segment_ticks = game.rules["segment_ticks"]
    segments, segment_kos, stalls = 0, 0, 0
    for tick in range(ticks):
        game.step()
        for name in names:
            alive[name] += game.state["fighters"][name]["state"] == "alive"
        segment_kos += sum(1 for e in game.state["events"] if e["kind"] == "ko")
        if (tick + 1) % segment_ticks == 0:
            segments += 1
            stalls += segment_kos == 0
            segment_kos = 0
    out = {}
    for side in ("b", "d"):
        members = [n for n in names if group[n] == side]
        fighters = [game.state["fighters"][n] for n in members]
        out[side] = {"n": len(members), "kos": sum(f["kos"] for f in fighters),
                     "deaths": sum(f["deaths"] for f in fighters), "alive": sum(alive[n] for n in members),
                     "lives": sum(f["deaths"] + 1 for f in fighters)}
    out["segments"], out["stalls"] = segments, stalls
    return out


def ratio(num, den):
    """A whole percent (num / den x 100, floored), so the report carries no floats."""
    return None if not den else num * 100 // den


def mixed(name, raw, size, seeds, ticks, rules=sim.DEFAULT_RULES):
    count = max(1, size // 2)
    rows = [run(seed, size, raw, count, ticks, rules) for seed in range(1, seeds + 1)]
    tot = {side: {k: sum(r[side][k] for r in rows) for k in ("n", "kos", "deaths", "alive", "lives")} for side in "bd"}
    kos, deaths = tot["b"]["kos"] + tot["d"]["kos"], tot["b"]["deaths"] + tot["d"]["deaths"]
    pop = ratio(tot["b"]["n"], tot["b"]["n"] + tot["d"]["n"])
    life_b, life_d = ratio(tot["b"]["alive"], tot["b"]["lives"]), ratio(tot["d"]["alive"], tot["d"]["lives"])
    report = {"behaviour": name, "size": size, "seeds": seeds, "ticks": ticks, "on_behaviour": count,
              "kos": [tot["b"]["kos"], tot["d"]["kos"]], "deaths": [tot["b"]["deaths"], tot["d"]["deaths"]],
              "pop_share_pct": pop,
              "ko_share_pct": ratio(tot["b"]["kos"], kos), "death_share_pct": ratio(tot["b"]["deaths"], deaths),
              "ko_index_x100": None if not kos else tot["b"]["kos"] * 100 * (tot["b"]["n"] + tot["d"]["n"]) // (kos * tot["b"]["n"]),
              "survival_per_life_ticks": [None if life_b is None else life_b // 100, None if life_d is None else life_d // 100],
              "survival_index_x100": None if not life_d else life_b * 100 // life_d,
              "distinct_outcomes": len({(r["b"]["kos"], r["d"]["kos"], r["b"]["deaths"], r["d"]["deaths"]) for r in rows})}
    if size == 2:
        wins = sum(r["b"]["kos"] > r["d"]["kos"] for r in rows)
        losses = sum(r["b"]["kos"] < r["d"]["kos"] for r in rows)
        report["duel"] = {"wins": wins, "losses": losses, "ties": seeds - wins - losses,
                          "win_pct_of_decided": ratio(wins, wins + losses)}
    return report


def stall(name, raw, size, seeds, ticks, rules=sim.DEFAULT_RULES):
    rows = [run(seed, size, raw, size if raw is not None else 0, ticks, rules) for seed in range(1, seeds + 1)]
    segs, stalls = sum(r["segments"] for r in rows), sum(r["stalls"] for r in rows)
    kos = sum(r["b"]["kos"] + r["d"]["kos"] for r in rows)
    return {"behaviour": name, "size": size, "seeds": seeds, "segments": segs, "stalled_segments": stalls,
            "stall_pct": ratio(stalls, segs), "kos_per_minute_x100": kos * 100 * 60 * rules["tick_hz"] // max(1, ticks * seeds),
            "distinct_outcomes": len({(r["b"]["kos"], r["d"]["kos"], r["stalls"]) for r in rows})}


def flags(report):
    out = []
    for row in report["mixed"]:
        duel = row.get("duel")
        won = None if not duel else duel["win_pct_of_decided"]
        if won is not None and (won > FAIR_1V1_TARGET or 100 - won > FAIR_1V1_TARGET):   # either side of the pair
            side = "the behaviour" if won > FAIR_1V1_TARGET else "the default AI"
            out.append({"behaviour": row["behaviour"], "size": 2, "field": "1v1 win rate (P3 target, not a gate)",
                        "value": f"{duel['wins']}-{duel['losses']}-{duel['ties']} (W-L-T), {won}% of decided: {side} wins more",
                        "bar": f"each side <= {FAIR_1V1_TARGET}%", "distinct_outcomes": row["distinct_outcomes"]})
        if row["size"] > 2 and row["ko_index_x100"] is not None and row["ko_index_x100"] > SHARE_BAR * 100:
            out.append({"behaviour": row["behaviour"], "size": row["size"], "field": "KO share / ring share (P3/P4 bar)",
                        "value": f"{row['ko_index_x100'] / 100:.2f}x ({row['ko_share_pct']}% of KOs, {row['pop_share_pct']}% of ring)",
                        "bar": f"<= {SHARE_BAR}x", "distinct_outcomes": row["distinct_outcomes"]})
        if row["survival_index_x100"] is not None and row["survival_index_x100"] > SHARE_BAR * 100:
            out.append({"behaviour": row["behaviour"], "size": row["size"], "field": "survival per life / default's (P4 bar)",
                        "value": f"{row['survival_index_x100'] / 100:.2f}x ({row['survival_per_life_ticks'][0]} vs {row['survival_per_life_ticks'][1]} ticks)",
                        "bar": f"<= {SHARE_BAR}x", "distinct_outcomes": row["distinct_outcomes"]})
    for row in report["all"]:
        if row["stall_pct"] is not None and row["stall_pct"] >= STALL_FLAG_PCT:
            base = next(b for b in report["baseline"] if b["size"] == row["size"])
            out.append({"behaviour": row["behaviour"], "size": row["size"], "field": "stall (whole ring on it)",
                        "value": f"{row['stalled_segments']}/{row['segments']} segments with no KO ({row['stall_pct']}%); default ring {base['stall_pct']}%",
                        "bar": f"< {STALL_FLAG_PCT}%", "distinct_outcomes": row["distinct_outcomes"]})
    return out


def sweep(sizes=SIZES, seeds=None, ticks=TICKS, log=None, rules=sim.DEFAULT_RULES):
    seeds = seeds or SEEDS
    named = behaviours(rules)
    report = {"rules_hash": sim.digest(rules), "rules_version": rules["version"],
              "hit_var_pct": rules["hitVarPct"], "ticks_per_run": ticks,
              "seeds": {str(s): list(range(1, seeds[s] + 1)) for s in sizes},
              "behaviours": named, "mixed": [], "all": [], "baseline": []}
    for size in sizes:
        report["baseline"].append(stall("default", None, size, seeds[size], ticks, rules))
        for name, raw in named.items():
            report["mixed"].append(mixed(name, raw, size, seeds[size], ticks, rules))
            report["all"].append(stall(name, raw, size, seeds[size], ticks, rules))
            if log:
                log(f"{rules['version']} size {size} {name} done")
    report["flags"] = flags(report)
    return report


def _cell(value, scale=1):
    return "-" if value is None else (f"{value / scale:.2f}" if scale != 1 else str(value))


def markdown(report):
    lines = [f"## The sweep under {report['rules_version']} (`{report['rules_hash'][:8]}`)", "",
             f"Rules table `{report['rules_version']}` (`{report['rules_hash'][:8]}`), hit variance "
             f"{report['hit_var_pct']}%, {report['ticks_per_run']} ticks ({report['ticks_per_run'] // sim.DEFAULT_RULES['tick_hz']} s) per run, seeds "
             + ", ".join(f"{k}: 1-{len(v)}" for k, v in report["seeds"].items()) + ". Everyone wears the newcomer "
             "starter kit with the brawler style, so the behaviour is the only difference. Reproduce: "
             "`python3 -I near/arena/battle_balance.py --json near/arena/battle-balance.json --md near/arena/BATTLE-BALANCE.md`.",
             "", "Report only: nothing is tuned here. A nerf is a new rules table and Pat's call.", "",
             "### Flags", ""]
    if report["flags"]:
        lines += ["| Behaviour | Size | Field | Value | Bar | Distinct outcomes |", "|---|---|---|---|---|---|"]
        lines += [f"| {f['behaviour']} | {f['size']} | {f['field']} | {f['value']} | {f['bar']} | {f['distinct_outcomes']} |"
                  for f in report["flags"]]
    else:
        lines.append("None.")
    lines += ["", "### Behaviour vs default AI (half the ring each)", "",
              "KO and death share are the behaviour group's share of all KOs and deaths; ring share is its share of "
              "fighters. KO index = KO share / ring share (bar 2.00). Survival = mean ticks alive per life, behaviour "
              "vs default; its index is the ratio (bar 2.00). At size 2 the duel is W-L-T over seeds (more KOs in "
              "the run wins), against the 60% target.", "",
              "| Behaviour | Size | Ring share | KO share | Death share | KO index | Survival (b / d) | Survival index | 1v1 W-L-T | Distinct |",
              "|---|---|---|---|---|---|---|---|---|---|"]
    for r in report["mixed"]:
        duel = r.get("duel")
        lines.append(f"| {r['behaviour']} | {r['size']} | {r['pop_share_pct']}% | {_cell(r['ko_share_pct'])}% | "
                     f"{_cell(r['death_share_pct'])}% | {_cell(r['ko_index_x100'], 100)} | "
                     f"{r['survival_per_life_ticks'][0]} / {r['survival_per_life_ticks'][1]} | {_cell(r['survival_index_x100'], 100)} | "
                     + (f"{duel['wins']}-{duel['losses']}-{duel['ties']} ({_cell(duel['win_pct_of_decided'])}%)" if duel else "") +
                     f" | {r['distinct_outcomes']} |")
    lines += ["", "### Stalls (the whole ring on one behaviour)", "",
              "A stalled segment is 60 s with no KO.", "",
              "| Behaviour | Size | Stalled segments | Stall % | KOs per minute | Distinct |", "|---|---|---|---|---|---|"]
    for r in report["baseline"] + report["all"]:
        lines.append(f"| {r['behaviour']} | {r['size']} | {r['stalled_segments']}/{r['segments']} | {_cell(r['stall_pct'])}% | "
                     f"{_cell(r['kos_per_minute_x100'], 100)} | {r['distinct_outcomes']} |")
    return "\n".join(lines) + "\n"


TABLES = ("integer-13", "integer-14")


def table(version):
    """A shipped rules table by its file name; the sweep never edits one."""
    rules = json.loads((Path(__file__).parent / "rules" / f"{version}.json").read_bytes())
    sim.validate_rules(rules)
    return sim.freeze(rules)


def load_runs(path):
    """Earlier runs kept in the JSON, keyed by table version (a one-table report is read as that table's run)."""
    if path is None or not path.exists():
        return {}
    data = json.loads(path.read_text())
    return data["tables"] if "tables" in data else {data["rules_version"]: data}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--json")
    parser.add_argument("--md")
    parser.add_argument("--tables", default=",".join(TABLES),
                        help="tables to sweep now (default: all); runs of other tables already in --json are kept")
    parser.add_argument("--quick", action="store_true", help="2 seeds per size, 1200 ticks: a smoke run, not the report")
    args = parser.parse_args(argv)
    seeds = {s: 2 for s in SIZES} if args.quick else SEEDS
    runs = load_runs(Path(args.json) if args.json else None)
    for version in args.tables.split(","):
        runs[version] = sweep(seeds=seeds, ticks=1200 if args.quick else TICKS, rules=table(version),
                              log=lambda m: print(m, file=sys.stderr, flush=True))
    ordered = {v: runs[v] for v in sorted(runs, key=lambda v: int(v.split("-")[1]))}
    if args.json:
        Path(args.json).write_text(json.dumps({"tables": ordered}, indent=1, sort_keys=True) + "\n")
    if args.md:
        path = Path(args.md)
        kept = path.read_text().split(MARKER)[0] if path.exists() and MARKER in path.read_text() else ""
        path.write_text(kept + MARKER + "\n\n" + "\n".join(markdown(r) for r in ordered.values()))
    print(json.dumps({v: r["flags"] for v, r in ordered.items()}, indent=1))


if __name__ == "__main__":
    main()
