#!/usr/bin/env python3
"""Pin the v1 starter portraits and immutable attributes in the NFT contract.

Run from the repo root after render_nft_media.cjs. Never replace published v1 bytes;
new art or starter kits need a new version and an explicit contract upgrade.
"""
import base64
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from near.arena import presets, sim


def main() -> None:
    near = ROOT / 'near'
    dest = near / 'nft/v1'
    opts = json.loads((near / 'web/snapin/premint/meta/options.json').read_text())
    kits = {p['name'].lower().replace(' ', '-'): p for p in presets.all_presets(sim.DEFAULT_RULES)}
    (dest / 'starter-kits.json').write_text(json.dumps(kits, indent=2) + '\n')
    if not all((dest / f'{slug}.png').is_file() for slug in opts):
        print('starter-kits.json ready; render portraits next')
        return
    rows = []
    for slug, meta in opts.items():
        kit = kits[slug]
        ref = {'schema': 'trenchie.identity.v1', 'preset': slug,
               'description': 'Starter appearance and loadout. Live gear and records are on testnet under the same token id.',
               'attributes': [{'trait_type': 'Fighting style', 'value': kit['style']},
                              {'trait_type': 'Weapon move', 'value': kit['weapon_kind']},
                              {'trait_type': 'Signature', 'value': kit['signature']},
                              *[{'trait_type': 'Starter ' + slot, 'value': item} for slot, item in kit['loadout'].items()]],
               'identity_contract': 'nft.trenchie-arena.near', 'identity_network': 'mainnet',
               'inventory_network': 'testnet', 'inventory_key': 'same token_id as the identity NFT'}
        (dest / f'{slug}.json').write_text(json.dumps(ref, separators=(',', ':'), ensure_ascii=False) + '\n')
        media_hash = base64.b64encode(hashlib.sha256((dest / f'{slug}.png').read_bytes()).digest()).decode()
        rows.append((slug, meta['name'], media_hash))
    lines = ['// Generated by near/tools/prepare_nft_metadata.py; v1 asset bytes are immutable.',
             'pub fn preset_media(preset: &str) -> Option<(&\'static str, &\'static str, &\'static str, &\'static str)> {',
             '    match preset {']
    for i, (slug, name, digest) in enumerate(rows, 1):
        lines.append(f'        "{slug}" | "preset-{i}" => Some(("{slug}", "{name}", "{digest}", include_str!("../../../nft/v1/{slug}.json"))),')
    lines += ['        _ => None,', '    }', '}']
    (near / 'contracts/trenchie_nft/src/media.rs').write_text('\n'.join(lines) + '\n')
    print('5 metadata references and contract media manifest pinned')


if __name__ == '__main__':
    main()
